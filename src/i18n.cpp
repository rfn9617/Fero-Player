void setLanguage(const QString &code) {
    language = code == QLatin1String("ru") ? QStringLiteral("ru") : QStringLiteral("en");
}

QString currentLanguage() {
    return language;
}

QString L(const char *russian) {
    const QString source = QString::fromUtf8(russian);
    if (language == QLatin1String("ru"))
        return source;
    return english().value(source, source);
}
